"""Generate the PDFKit outline fixture from the existing read-only rotation sample."""
import io
import json
from pathlib import Path

from pypdf import PdfReader, PdfWriter

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'android-app/src/androidTest/assets/pdf/crop-rotations.pdf'
RECIPE = ROOT / 'fixtures/pdf/outline-recipe.json'
OUTPUT = ROOT / 'fixtures/pdf/outline-destinations.pdf'


def read_outline(reader):
    def read(entries):
        nodes = []
        for entry in entries:
            if isinstance(entry, list):
                nodes[-1]['children'] = read(entry)
            else:
                nodes.append({'title': entry.title, 'source_index': reader.get_destination_page_number(entry),
                              'children': []})
        return nodes

    return read(reader.outline)


def main():
    original = SOURCE.read_bytes()
    src = PdfReader(io.BytesIO(original))
    writer = PdfWriter()
    for page in src.pages:
        writer.add_page(page)
    expected = json.loads(RECIPE.read_text(encoding='utf-8'))

    def add(entries, parent=None):
        for entry in entries:
            handle = writer.add_outline_item(entry['title'], entry['source_index'], parent=parent)
            add(entry['children'], handle)

    add(expected)
    buffer = io.BytesIO()
    writer.write(buffer)
    data = buffer.getvalue()
    result = PdfReader(io.BytesIO(data))

    assert read_outline(result) == expected
    assert len(src.pages) == len(result.pages) == 4
    for before, after in zip(src.pages, result.pages):
        assert before.get_contents().get_data() == after.get_contents().get_data()
        assert before.rotation == after.rotation and list(before.cropbox) == list(after.cropbox)
    assert SOURCE.read_bytes() == original
    if OUTPUT.exists() and OUTPUT.read_bytes() != data:
        raise ValueError('existing outline fixture differs from generated bytes')
    OUTPUT.write_bytes(data)


if __name__ == '__main__':
    main()
