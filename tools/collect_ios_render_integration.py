#!/usr/bin/env python3
"""Bind manual CUA observations and retained runtime evidence; never promotes fallback to backend acceptance."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(relative):
    return json.loads((ROOT / relative).read_text(encoding='utf-8'))


def main():
    runtime = read('reports/ios-runtime-smoke.json')
    build = read('reports/ios-preview-build.json')
    restored = read('reports/ios-preview-restored.json')
    host = read('reports/ios-host-tests.json')
    notes = read('build/dev036c-test-document.json')
    assert all(r['status'] == 'passed' for r in (runtime, build, restored, host))
    assert runtime['artifact_sha256'] == restored['artifact_sha256'] == build['sha256']
    assert digest(ROOT / build['artifact']) == build['sha256']
    for relative, sha in build['source_and_build_input_sha256'].items():
        assert digest(ROOT / relative) == sha, ('Stale ordinary build', relative)
    for field in ('source_and_framework_sha256', 'test_build_sha256'):
        for relative, sha in host[field].items():
            assert digest(ROOT / relative) == sha, ('Stale host evidence', relative)
    assert host['test_count'] == 22 and host['preview_model_view_lifecycle_test_count'] == 4
    assert restored['no_xctest_plugin'] and not restored['data_deleted']
    assert notes['all_original_files_unchanged'] and notes['original_file_count'] == 5
    assert (notes['pages'], notes['total_strokes'], notes['page_strokes']) == (2, 3, [2, 1])
    source = ROOT / 'build/dev036c-render-stream.log'
    events = []
    for line in source.read_text(encoding='utf-8').splitlines():
        try:
            event = json.loads(line)
        except ValueError:
            continue
        message = event.get('eventMessage', '')
        if event.get('processID') == runtime['pid'] and message.startswith('NOTECORE_RENDER '):
            events.append({'timestamp': event['timestamp'], 'pid': runtime['pid'], 'message': message})
    rejected = [e for e in events if e['message'] == 'NOTECORE_RENDER target-rejected non-bitmap']
    presented = [e for e in events if 'frame-presented' in e['message']]
    assert rejected and not presented, 'This report is the measured rejected-target branch, not successful screen integration'
    report = {
        'schema': 'ios-render-integration-1', 'status': 'evidence_verified_integration_blocked',
        'artifact_sha256': build['sha256'], 'ordinary_pid': runtime['pid'],
        'device': runtime['device'], 'runtime_events': events,
        'runtime_event_scope': 'Events selected by ordinary-package PID, excluding XCTest host events. Message names the CPU gate rejection: context.data was nil; this does not identify the hardware backend or prove a GPU fence.',
        'host_test_count': 22, 'model_cpu_view_lifecycle_tests': 4,
        'model_shared_executor_cpu_view_verified': True,
        'ordinary_screen_new_backend_consumption_verified': False,
        'ordinary_screen_cpu_gate_rejection_verified': True,
        'fallback_ui_observation_method': 'Manual CUA through Device Hub com.apple.dt.Devices; observations recorded from actual AX/UI actions, not generated by this collector or inferred from test counts.',
        'fallback_ui_observations': [
            'Final ordinary package reopened DEV036C-UIView-20261016 at page 1/1 with 2 existing strokes. Initial creation/rename/two strokes preceded the final DEBUG-flag rebuild and are fixture preparation only; their UI acceptance is not transferred to the final package.',
            'Added page: page 2/2 showed 0 strokes; actual drag saved 1 stroke, total saved 3.',
            'Returned to page 1/2: 2 strokes; zoom in/out and fit page retained the page contents.',
            'Device Hub Home showed system app icons; reopening NoteCore retained page 1/2 and 2 strokes.',
            'Returned to library and reopened named file: opened total 3, page 1/2 canvas 2 strokes.',
        ],
        'test_document': notes,
        'source_evidence_sha256': {relative: digest(ROOT / relative) for relative in (
            'reports/ios-preview-build.json', 'reports/ios-preview-restored.json',
            'reports/ios-host-tests.json', 'reports/ios-runtime-smoke.json',
            'build/dev036c-ui-baseline.json', 'build/dev036c-test-document.json',
            'build/dev036c-render-stream.log', 'tools/collect_ios_render_integration.py')},
        'scope': 'Complete ink frames and same-model close/ACK/UNKNOWN responsibility are validated in CPU UIKit host targets. Ordinary screen destination rejects the CPU holder and uses the complete legacy Path fallback. The new screen backend is NOT accepted; no physical stylus/frame/heap/GPU, C1, SQLite, forced-stop or new backup-picker acceptance.',
        'c1_gate_complete': False, 'physical_device_or_heap_or_gpu_measured': False,
    }
    (ROOT / 'reports/ios-render-integration.json').write_text(json.dumps(report, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(json.dumps({'status': report['status'], 'ordinary_pid': runtime['pid'],
                      'rejected_events': len(rejected), 'presented_events': len(presented),
                      'original_files_unchanged': notes['original_file_count'], 'page_strokes': notes['page_strokes']}))


if __name__ == '__main__':
    main()
